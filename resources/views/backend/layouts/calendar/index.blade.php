                renderMiniCalendar();

                const todayStr = new Date().toISOString().split('T')[0];
                const todayEl = document.querySelector(`.mini-calendar-day[data-date="${todayStr}"]`);
                if (todayEl) {
                    todayEl.classList.add('selected');
                }
            });

