    <script>
        document.addEventListener('DOMContentLoaded', function() {
            const calendarEl = document.getElementById('calendar');
            let currentEventId = null;
            let selectedDates = [];
            let miniCalendarDate = new Date();
            let autocomplete;

            // Initialize Google Places Autocomplete
            function initAutocomplete() {
                const input = document.getElementById('location');

                // Clear any existing autocomplete
                if (autocomplete) {
                    google.maps.event.clearInstanceListeners(input);
                }

                // Create new autocomplete instance
                autocomplete = new google.maps.places.Autocomplete(input, {
                    types: ['geocode', 'establishment'],
                    fields: ['formatted_address', 'geometry', 'name']
                });

                // Listen for place selection
                autocomplete.addListener('place_changed', function() {
                    const place = autocomplete.getPlace();

                    if (!place.geometry) {
                        showToast('No details available for: ' + place.name, 'error');
                        return;
                    }

                    if (place.geometry) {
                        const lat = place.geometry.location.lat();
                        const lng = place.geometry.location.lng();

                        document.getElementById('latitude').value = lat;
                        document.getElementById('longitude').value = lng;
                        document.getElementById('location').value = place.formatted_address || place.name;

                        console.log('Location selected:', {
                            address: place.formatted_address || place.name,
                            lat: lat,
                            lng: lng
                        });
                    }
                });
            }

            // Wait for Google Maps to load before initializing
            function waitForGoogleMaps(callback) {
                if (typeof google !== 'undefined' && google.maps && google.maps.places) {
                    callback();
                } else {
                    setTimeout(() => waitForGoogleMaps(callback), 100);
                }
            }

            // Initialize autocomplete when ready
            waitForGoogleMaps(function() {
                initAutocomplete();
            });

            // Re-initialize autocomplete when modal opens
            $('#createWorkModal').on('shown.bs.modal', function() {
                setTimeout(function() {
                    waitForGoogleMaps(function() {
                        initAutocomplete();
                    });
                }, 300);
            });

            // Initialize FullCalendar
            const calendar = new FullCalendar.Calendar(calendarEl, {
                initialView: 'dayGridDay',
                headerToolbar: false,
                editable: true,
                selectable: true,
                selectMirror: true,
                dayMaxEvents: true,
                weekends: true,
                height: '100%',
                displayEventTime: false,
                events: {
                    url: '{{ route('calendar.events') }}',
                    method: 'GET',
                    extraParams: function() {
                        return {
                            team_id: $('#teamFilter').val(),
                            status: $('#statusFilter').val(),
                            category_id: $('#categoryFilter').val()
                        };
                    },
                    failure: function() {
                        showToast('Failed to load events', 'error');
